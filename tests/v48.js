const {boot}=require('./harness');
const {w,errs,E,T,clear}=boot();
setTimeout(()=>{
 w.document.getElementById('startBtn').click();
 setTimeout(()=>{
  const iv=w.setInterval(clear,30);
  const ok=(l,c)=>console.log('  '+(c?'✓':'✗')+' '+l);
  const dlg=()=>w.eval('document.body.textContent||""');
  console.log('IT IS A HELPER FOR THE HUNT, NOT A SIDE QUEST');
  console.log('  1. no hunt open -> nothing to sell');
  T('S.gate=null;S.bounty=null;S.lira=99999;player.position.set(-24,6,-19);');
  T('offerContracts();');
  ok('he offers no contracts without an open hunt',!/each|Karışık/i.test(dlg().slice(-1200))||!w.eval('S.bounty'));
  ok('and says so warmly instead',/nothing for me to arrange|otur biraz/i.test(dlg()));
  T('if(typeof cancelDlg==="function")cancelDlg();');
  console.log('  2. he never sells more than the hunt still needs');
  T('S.gate={next:5,type:"ghost",left:2,eleft:0};S.bounty=null;');
  ok('gateNeeds() reads the hunt: '+w.eval('gateNeeds()'),w.eval('gateNeeds()')===2);
  T('pickCount(hireOf("ghost"));');
  const txt=dlg();
  ok('the count list is capped at what is left',/still wants <?b?>?2|still wants \*?\*?2/.test(txt)||/2/.test(txt));
  console.log('  3. the kills feed the SAME gate, no parallel objective');
  T('S.gate={next:5,type:"ghost",left:5,eleft:0};S.bounty=null;enemies.length=0;S.lira=99999;');
  const lira0=w.eval('S.lira');
  T('startBounty(CONTRACTS[2],hireOf("ghost"));');
  const fee=lira0-w.eval('S.lira');
  console.log('     finder\'s fee for 3 ghosts:',fee+'₺');
  ok('a finder\'s fee, not a job price',fee>0&&fee<1500);
  ok('the contract carries NO separate xp/lira reward',
     w.eval('S.bounty.xp')===undefined&&w.eval('S.bounty.lira')===undefined);
  T('player.position.set(S.bounty.x+8,0,S.bounty.z+8);updateBounty(.03);');
  ok('3 ghosts spawn',w.eval('enemies.length')===3&&w.eval('enemies.every(e=>e.type==="ghost")'));
  const g0=w.eval('S.gate.left'),l0=w.eval('S.lira'),x0=w.eval('S.xp');
  T('while(enemies.length)killEnemy(enemies[0]);updateBounty(.03);');
  console.log('     gate',g0,'->',w.eval('S.gate?S.gate.left:"cleared"'),
    '| lira',l0,'->',w.eval('S.lira'),'| xp',x0,'->',w.eval('S.xp'));
  ok('the kills came off the hunt',w.eval('S.gate.left')===g0-3);
  T('for(let i=0;i<200;i++)updateCoins(.05);');
  ok('she still got the normal kill rewards (xp '+x0+'->'+w.eval('S.xp')+', lira '+l0+'->'+w.eval('S.lira')+')',w.eval('S.lira')>l0&&w.eval('S.xp')>x0);
  ok('the delivery closed quietly, no completion banner',!w.eval('S.bounty'));
  console.log('  4. HUD reads as part of the hunt');
  T('S.bounty=null;enemies.length=0;startBounty(CONTRACTS[0],hireOf("ghost"));gateHUD();');
  const hud=w.eval('$("bountyT").innerHTML');
  console.log('     hunt line  :',w.eval('$("missionS").textContent'));
  console.log('     kaan line  :',hud.replace(/<[^>]+>/g,''));
  ok('the objective line is still the HUNT',/Defeat/.test(w.eval('$("missionS").textContent')));
  ok('Kaan\'s line is phrased as a hint, not an objective',/found/i.test(hud)&&!/CONTRACT/i.test(hud));
  console.log('  5. clearing the hunt calls off an undelivered batch');
  T('S.bounty=null;startBounty(CONTRACTS[0],hireOf("ghost"));');
  ok('delivery pending',!!w.eval('S.bounty'));
  T('S.gate.left=0;S.gate.eleft=0;gateComplete();');
  ok('hunt cleared -> Kaan calls them off',!w.eval('S.bounty'));
  console.log('  6. still only sends the species she paid for');
  T('S.gate={next:5,type:"mummy",left:4,eleft:0};S.bounty=null;enemies.length=0;S.lira=99999;');
  T('startBounty(CONTRACTS[3],hireOf("mummy"));player.position.set(S.bounty.x+8,0,S.bounty.z+8);updateBounty(.03);');
  ok('4 mummies, all of them',w.eval('enemies.length')===4&&w.eval('enemies.every(e=>e.type==="mummy")'));
  w.clearInterval(iv);
  console.log(E.length?'ERRORS: '+[...new Set(E)].slice(0,4).join(' ;; '):'NO ERRORS ✓');
  console.log(errs.length?'RUNTIME: '+[...new Set(errs)].slice(0,3).join(' ;; '):'NO RUNTIME ERRORS ✓');
  process.exit(0);
 },3200);
},2000);
setTimeout(()=>{console.log('TIMEOUT');process.exit(2);},40000);
