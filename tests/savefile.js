const {boot}=require('./harness');
const {w,errs,E,T,clear}=boot();
setTimeout(()=>{
 w.document.getElementById('startBtn').click();
 setTimeout(()=>{
  const iv=w.setInterval(clear,30);
  const ok=(l,c)=>console.log('  '+(c?'✓':'✗')+' '+l);
  console.log('SAVING TO A REAL FILE');
  T('S.level=9;S.lira=4321;S.unit=6;S.kills=88;saveGame();');
  // capture what the download would produce
  T(`window.__dl=null;
     URL.createObjectURL=function(b){window.__dl={size:b.size,type:b.type};return 'blob:x';};
     URL.revokeObjectURL=function(){};
     HTMLAnchorElement.prototype.click=function(){window.__dl.name=this.download;};`);
  T('openBackup();downloadSave();');
  console.log('   file:',w.eval('__dl&&__dl.name'),'|',w.eval('__dl&&__dl.type'),'|',w.eval('__dl&&__dl.size')+' bytes');
  ok('it downloads a file',!!w.eval('__dl'));
  ok('named with her level and the date',/torii-save-lvl9-\d{8}-\d{4}\.json/.test(w.eval('__dl.name')||''));
  ok('as plain JSON, not base64',w.eval('__dl.type')==='application/json');
  console.log('\nLOADING IT BACK');
  const raw=w.eval('localStorage.getItem(SAVE_KEY)');
  T('localStorage.removeItem(SAVE_KEY);localStorage.removeItem(SAVE_KEY+"_bak");localStorage.removeItem(SAVE_KEY+"_bak2");');
  ok('storage wiped, as if the browser cleared it',!w.eval('localStorage.getItem(SAVE_KEY)'));
  T('applySaveText('+JSON.stringify(raw)+',"a file");');
  const back=JSON.parse(w.eval('localStorage.getItem(SAVE_KEY)')||'null');
  console.log('   restored: level',back&&back.lvl,'| lira',back&&back.lira,'| unit',back&&back.unit,'| kills',back&&back.kills);
  ok('everything comes back',back&&back.lvl===9&&back.lira===4321&&back.unit===6&&back.kills===88);
  console.log('   message:',w.eval('$("bkMsg").textContent'));
  console.log('\nIT ALSO STILL ACCEPTS THE OLD TRANSFER CODE');
  const b64=w.eval('btoa(unescape(encodeURIComponent(localStorage.getItem(SAVE_KEY))))');
  T('localStorage.removeItem(SAVE_KEY);');
  T('applySaveText('+JSON.stringify(b64)+',"the code");');
  ok('base64 still works, same function',JSON.parse(w.eval('localStorage.getItem(SAVE_KEY)')||'null').lvl===9);
  console.log('\nIT REFUSES RUBBISH');
  T('applySaveText("just some text I found","x");');
  ok('a random file is rejected',/does not look like/.test(w.eval('$("bkMsg").textContent')));
  T('applySaveText(JSON.stringify({hello:1}),"x");');
  ok('valid JSON that is not a Torii save is rejected too',/does not look like/.test(w.eval('$("bkMsg").textContent')));
  ok('and the existing save was not damaged',JSON.parse(w.eval('localStorage.getItem(SAVE_KEY)')||'null').lvl===9);
  console.log('\nDRAG AND DROP');
  ok('drop handler wired',w.eval('typeof applySaveText')==='function');
  T(`document.body.classList.remove('dropping');
     window.dispatchEvent(Object.assign(new Event('dragover'),{preventDefault(){}}));`);
  ok('dragging a file over the window shows a target',w.eval('document.body.classList.contains("dropping")'));
  console.log('\nPERSISTENT STORAGE');
  ok('the game asks the browser to keep its storage',w.eval('typeof askPersist')==='function');
  console.log('   (Chromium and Firefox honour navigator.storage.persist; Safari ignores it,');
  console.log('    which is exactly why the file matters)');
  w.clearInterval(iv);
  console.log(E.length?'ERRORS: '+[...new Set(E)].slice(0,3).join(' ;; '):'NO ERRORS ✓');
  console.log(errs.length?'RUNTIME: '+[...new Set(errs)].slice(0,2).join(' ;; '):'NO RUNTIME ERRORS ✓');
  process.exit(0);
 },2800);
},2000);
setTimeout(()=>{console.log('TIMEOUT');process.exit(2);},40000);
