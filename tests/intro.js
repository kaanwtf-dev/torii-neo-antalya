// ALPHA 7.0 — the 80s intro: VHS gate, the timeline, skipping, and the hand-off to the game
const {boot}=require('./harness');
const wait=ms=>new Promise(r=>setTimeout(r,ms));
const ok=(l,c)=>console.log('  '+(c?'✓':'✗')+' '+l);
const key=(w,k)=>w.dispatchEvent(new w.KeyboardEvent('keydown',{key:k,bubbles:true}));
(async()=>{
 let {w,errs,E,T}=boot();const g=k=>w.eval(k);
 await wait(1600);
 console.log('1. THE VHS GATE');
 ok('the game opens on the intro, not the menu',g('INTRO.ph')==='vhs'&&!g('$("title").classList.contains("menu")'));
 ok('the menu is there but hidden until the intro is done',g('getComputedStyle($("tMenu")).opacity')==='0');
 key(w,'Escape');
 ok('ESC does not count as "any key" (browsers won\'t allow sound on it)',g('INTRO.ph')==='vhs');
 key(w,'a');
 ok('any other key starts it',g('INTRO.ph')==='play');
 ok('...and the synthwave track is playing',!!g('IM.t'));
 ok('the game music is NOT started yet',!g('musT'));
 await wait(300);
 console.log('\n2. SKIP');
 key(w,'x');
 ok('a second key skips straight to the menu',g('INTRO.ph')==='menu'&&g('$("title").classList.contains("menu")'));
 ok('the track keeps playing under the menu',!!g('IM.t'));
 key(w,'b');
 ok('keys on the menu do nothing strange',g('INTRO.ph')==='menu'&&g('S.mode')==='title');
 console.log('\n3. INTO THE GAME');
 T('$("startBtn").click()');await wait(200);
 ok('NEW GAME ends the intro',g('INTRO.ph')==='done'&&g('S.mode')==='play');
 ok('the intro track stops, the game music starts',!g('IM.t')&&!!g('musT'));
 w.close();
 ({w,errs,E,T}=boot());
 await wait(1600);
 console.log('\n4. LEFT ALONE, IT PLAYS THROUGH');
 key(w,'Enter');await wait(100);
 T('INTRO.t0=now()-19.5');await wait(200);
 ok('after the cast cards it lands on the menu by itself',w.eval('INTRO.ph')==='menu');
 ok('no errors from the intro',!E.length&&!errs.length);
 if(E.length||errs.length)console.log([...E,...errs].slice(0,4).join(' ;; '));
 console.log(E.length?'ERRORS':'NO ERRORS ✓');
 process.exit(0);
})();
setTimeout(()=>{console.log('TIMEOUT');process.exit(2);},30000);
